  // 現在の言語の辞書を返す（未設定や未知の言語は ja にフォールバック）
  function dict() {
    var lang = global.LANG || 'ja';
    return I18N[lang] || I18N.ja;
  }

  // 選択中のドロッパー種類に応じた言い換え語（{ev}=催しの呼び名 / {doc}=配布物の呼び名）。
  // 例：スポーツなら「大会」「要項」、コンサートなら「公演」「チラシ」。
  // 未選択のうちは汎用の語（イベント／チラシ）を使う。
  var terms = {};
  function setTerms(o) { terms = o || {}; }

  // キーから文言を引く（{ev}/{doc} は自動、vars を渡すと {name} 形式も置換）
  function t(key, vars) {
    var d = dict();
    var s = (key in d) ? d[key] : ((key in I18N.ja) ? I18N.ja[key] : key);
    var all = { ev: terms.ev || d.evGeneral || '', doc: terms.doc || d.docGeneral || '' };
    if (vars) { for (var k in vars) { all[k] = vars[k]; } }
    for (var k2 in all) { s = s.split('{' + k2 + '}').join(all[k2]); }
    return s;
  }

  // data-i18n 属性を持つ要素に文言を流し込む。data-i18n-attr があればその属性に、なければテキストに。
  function applyDom() {
    document.title = t('pageTitle');
    // <html lang> は3フォルダとも 'ja' のまま（index.html を同一に保つ決まりのため）。
    // そのままだと en/in が「日本語のページ」と宣言することになり、sitemap の hreflang と
    // 食い違ううえ、読み上げも誤った言語になる。表示言語に合わせてここで書き換える。
    // in が 'en-IN' なのは sitemap の hreflang に合わせているため（勝手に変えない）。
    try {
      document.documentElement.lang = (global.LANG === 'en') ? 'en' : (global.LANG === 'in') ? 'en-IN' : 'ja';
    } catch (e) {}
    // 使い方ガイドは3言語とも公開済み。リンク先を言語別に切り替える。
    var gl = document.getElementById('guideLink');
    if (gl) {
      var a = gl.querySelector('a');
      if (a) {
        var gp = (global.LANG === 'en') ? 'en/guide.html' : (global.LANG === 'in') ? 'in/guide.html' : 'guide.html';
        a.href = 'https://dropper-tools.com/' + gp;
      }
    }
    // APIキーの案内ページ（周知サイト）。AI利用ポップアップとAPIキー入力の2か所を、
    // 同じ言語の版へ送る。HTMLに直書きの href は ja 用の既定値。
    var akPath = (global.LANG === 'en') ? 'en/apikey.html' : (global.LANG === 'in') ? 'in/apikey.html' : 'apikey.html';
    var akIds = ['aiKeyGuideLink', 'keyMoreLink'];
    for (var ak = 0; ak < akIds.length; ak++) {
      var akEl = document.getElementById(akIds[ak]);
      if (akEl) { akEl.href = 'https://dropper-tools.com/' + akPath; }
    }
    // ドロッパー切り替えタブ。予定表ドロッパーは3言語そろったので、どの言語でも出す。
    // リンク先は同じ言語の版へ送ること（en から ja の予定表へ飛ばさない）。
    var ts = document.getElementById('tabSchedule');
    if (ts) {
      ts.href = (global.LANG === 'en') ? '/schedule-en/' : (global.LANG === 'in') ? '/schedule-in/' : '/schedule/';
    }
    var td = document.getElementById('tabDecide');
    if (td) {
      td.href = (global.LANG === 'en') ? '/decide-en/' : (global.LANG === 'in') ? '/decide-in/' : '/decide/';
    }
    // 「何ができる？」ポップアップの「使ってみる」。タブと同じく同じ言語の版へ送る。
    // タブと同じ規則なので、リンク先を変えるときは両方そろえること。
    var tmGoS = document.getElementById('tmGoSchedule');
    if (tmGoS) {
      tmGoS.href = (global.LANG === 'en') ? '/schedule-en/' : (global.LANG === 'in') ? '/schedule-in/' : '/schedule/';
    }
    var tmGoD = document.getElementById('tmGoDecide');
    if (tmGoD) {
      tmGoD.href = (global.LANG === 'en') ? '/decide-en/' : (global.LANG === 'in') ? '/decide-in/' : '/decide/';
    }
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
      var key = els[i].getAttribute('data-i18n');
      var attr = els[i].getAttribute('data-i18n-attr');
      var val = t(key);
      if (attr) { els[i].setAttribute(attr, val); }
      else { els[i].textContent = val; }
    }
  }

  global.I18N = { t: t, dict: dict, applyDom: applyDom, setTerms: setTerms };

